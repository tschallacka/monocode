#!/usr/bin/env bash
set -euo pipefail

# Builds MonoCode in the flake's dev shell and installs it for the current user
# under ~/.local. The binary links against the shell's Nix libraries, so the
# shell is kept as a profile (a GC root) that garbage collection leaves alone,
# and a launcher sets the GL drivers and GSettings schemas Nix's GTK and WebKit
# need outside NixOS.

if [ "$(uname)" != "Linux" ]; then
  echo "This helper only supports Linux." >&2
  exit 1
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROFILE="${XDG_STATE_HOME:-$HOME/.local/state}/nix/profiles/monocode-dev"
LIB_DIR="$HOME/.local/lib/monocode"
BIN_DIR="$HOME/.local/bin"
APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
ICONS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor"
NIX=(nix --extra-experimental-features 'nix-command flakes')

cd "$ROOT"
mkdir -p "$(dirname "$PROFILE")"
if [ "${1:-}" != "--skip-build" ]; then
  # Local builds have no updater signing key; skip the updater archive.
  "${NIX[@]}" develop --profile "$PROFILE" -c \
    npx tauri build --no-bundle --config '{"bundle":{"createUpdaterArtifacts":false}}'
elif [ ! -e "$PROFILE" ]; then
  # A build from a plain `nix develop` still needs its libraries kept alive.
  "${NIX[@]}" develop --profile "$PROFILE" -c true
fi

BUILT="$ROOT/target/release/monocode"
if [ ! -x "$BUILT" ]; then
  echo "No binary at $BUILT" >&2
  exit 1
fi

shell_env() {
  "${NIX[@]}" develop "$PROFILE" -c printenv "$1"
}

# Every GSettings schema directory in the shell, for GTK's file dialogs.
schemas=""
for path in $(nix-store -qR "$PROFILE"); do
  for dir in "$path"/share/gsettings-schemas/*; do
    if [ -d "$dir/glib-2.0/schemas" ]; then schemas="$schemas$dir:"; fi
  done
done

mkdir -p "$LIB_DIR" "$BIN_DIR" "$APPS_DIR"
install -m 755 "$BUILT" "$LIB_DIR/monocode.new"
mv -f "$LIB_DIR/monocode.new" "$LIB_DIR/monocode"

cat > "$BIN_DIR/monocode" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install-linux-nix.sh.
export __EGL_VENDOR_LIBRARY_FILENAMES="$(shell_env __EGL_VENDOR_LIBRARY_FILENAMES)"
export LIBGL_DRIVERS_PATH="$(shell_env LIBGL_DRIVERS_PATH)"
export GBM_BACKENDS_PATH="$(shell_env GBM_BACKENDS_PATH)"
export LD_LIBRARY_PATH="$(shell_env LD_LIBRARY_PATH)\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export XDG_DATA_DIRS="$schemas\${XDG_DATA_DIRS:-/usr/local/share:/usr/share}"
cd "\$HOME"
exec "$LIB_DIR/monocode" "\$@"
EOF
chmod 755 "$BIN_DIR/monocode"

install -Dm 644 src-tauri/icons/32x32.png "$ICONS_DIR/32x32/apps/monocode.png"
install -Dm 644 src-tauri/icons/128x128.png "$ICONS_DIR/128x128/apps/monocode.png"
install -Dm 644 src-tauri/icons/128x128@2x.png "$ICONS_DIR/256x256/apps/monocode.png"

cat > "$APPS_DIR/monocode.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=MonoCode
Exec=$BIN_DIR/monocode
Icon=monocode
Categories=Development;
Terminal=false
StartupWMClass=monocode
EOF
update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true

echo "Installed MonoCode: $BIN_DIR/monocode (menu entry: MonoCode)"
